test('OTP attempts persist, codes expire, replay fails, and tokens use isolated customer UIDs', async () => {
  const minted = [];
  const handlers = portalHandlers(db, { createCustomToken: async (uid, claims) => { minted.push({ uid, claims }); return 'test-token'; } });
  const challengeId = 'a'.repeat(48), code = '123456';
  const challenge = db.doc(`rlPortalChallenges/${challengeId}`);
  await challenge.set({ email: 'customer@workflows.test', codeHash: otpHash(challengeId, code), expiresAt: Timestamp.fromMillis(Date.now() + 600000), attempts: 0, consumed: false });
  for (let i = 0; i < 5; i++) await assert.rejects(handlers.verifyCustomerOTP({ rawRequest: { ip: 'test-ip' }, data: { challengeId, code: '000000' } }));
  await assert.rejects(handlers.verifyCustomerOTP({ data: { challengeId, code } }));
  await challenge.update({ attempts: 0 });
  assert.equal((await handlers.verifyCustomerOTP({ data: { challengeId, code } })).token, 'test-token');
  assert.ok(minted[0].uid.startsWith('rl_customer_')); assert.equal(minted[0].claims.portal, true);
  await assert.rejects(handlers.verifyCustomerOTP({ data: { challengeId, code } }));
  await challenge.update({ consumed: false, expiresAt: Timestamp.fromMillis(0) });
  await assert.rejects(handlers.verifyCustomerOTP({ data: { challengeId, code } }));
});
