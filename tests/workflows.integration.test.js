test('email worker leases prevent concurrent delivery and cancel paid invoice emails', async () => {
  const ref = db.doc('rlMail/worker-test');
  await ref.set({ to: 'test@workflows.test', subject: 'Test', text: 'Test', status: 'queued', availableAt: 0, expiresAt: Timestamp.fromMillis(Date.now() + 60000) });
  let sends = 0;
  const transport = { sendMail: async () => { sends++; return { accepted: ['test@workflows.test'] }; } };
  await Promise.all([deliverMail(db, ref, transport, 'from@workflows.test'), deliverMail(db, ref, transport, 'from@workflows.test')]);
  assert.equal(sends, 1); assert.equal((await ref.get()).get('status'), 'sent');
  await db.doc('invoices/paid-mail').set({ status: 'paid' });
  await ref.update({ status: 'queued', availableAt: 0, invoiceId: 'paid-mail' });
  await deliverMail(db, ref, transport, 'from@workflows.test');
  assert.equal(sends, 1); assert.equal((await ref.get()).get('status'), 'cancelled');
});
